#!/usr/bin/env node
// Generates every capability statement in the public READMEs and in the format
// table of `docs/18`, from the artifacts the code already maintains.
//
// Why this exists. The root README carried a hand-written feature list and a
// hand-written format table, and both fell weeks behind `main` (PDF import was
// listed as "—" after it had shipped; the MCP server, the header/footer and the
// object work were missing). A rule that says "update the README when you ship"
// is a rule somebody forgets, which is the defect `SKILL` §6a.4 names: a
// hand-maintained figure becomes a generated artifact. So nothing in the
// regions below is typed:
//
//   * `features` — the `docs/153` matrix, which `tools/opendoc-parity`
//     derives from `host_contract.mjs` and grep anchors into the code, and which
//     `cargo test -p opendoc-parity` fails when stale. Rows graded Parity, Ours
//     only and Ours, ungated are listed as shipped; Partial rows are listed with
//     the part that is missing, in the matrix's own words.
//   * `formats` and `support-formats` — the `FormatDescriptor` each
//     `casual-doc-io` adapter declares (`can_import`, `can_export`,
//     `exact_if_unchanged`), plus PDF import, which is a second registration
//     (`enable_pdf_import`) the editor reaches through its lazy PDF module. The
//     PDF claims are ANCHORS: a literal that must still be in a named file, so
//     the day it moves this generator throws instead of publishing a stale line.
//   * `agents` — the MCP tool catalogue (`tools/opendoc-mcp/src/catalog.rs`)
//     and the edit vocabulary (`webapp/generated/commands.json`, generated by
//     `opendoc-command-gen` from `casual-doc-command`).
//   * `viewer-formats` — the viewer package's default build features
//     (`packages/opendoc-viewer/build.sh`) and the crate's optional ones.
//
// It also CHECKS one hand-written table it does not generate: the README's crate
// table must name exactly the workspace's `crates/*` members plus the relay, so a
// new crate cannot ship without a line saying what it is for.
//
// Regions use the convention `build-embed-docs.mjs` set:
// `<!-- @generated NAME -->` … `<!-- @end NAME -->`. Everything outside them is
// hand-written prose and must not state capabilities or counts.
//
//   node webapp/tools/build-readme.mjs           rewrite the regions
//   node webapp/tools/build-readme.mjs --check   fail if any committed region is stale
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const read = (path) => readFileSync(join(REPO, path), "utf8");
const GENERATOR = "webapp/tools/build-readme.mjs";

/** Markdown table cells, with pipes inside code spans preserved (the same rule
 *  as `tests/tracker_parse.mjs`). */
export function cells(row) {
  const masked = row.replace(/`[^`]*`/g, (m) => m.replaceAll("|", "\u0000"));
  return masked
    .trim()
    .replace(/^\|/, "")
    .replace(/\|$/, "")
    .split("|")
    .map((c) => c.replaceAll("\u0000", "|").trim());
}

const SHIPPED = new Set(["Parity", "Ours only", "Ours, ungated"]);

/** The `docs/153` matrix, by area: `[{ title, shipped: [...], partial: [{title, missing}], gaps }]`. */
export function parityAreas(text = read("docs/153-ONLYOFFICE-CAPABILITY-PARITY-MATRIX.md")) {
  const start = text.indexOf("<!-- @generated parity-matrix -->");
  const end = text.indexOf("<!-- @end parity-matrix -->");
  if (start < 0 || end < start) throw new Error("docs/153: the parity-matrix region is missing");
  const areas = [];
  let area = null;
  for (const line of text.slice(start, end).split("\n")) {
    const heading = /^### (.+?) \(\d+ rows\)$/.exec(line);
    if (heading) {
      area = { title: heading[1], shipped: [], partial: [], gaps: 0 };
      areas.push(area);
      continue;
    }
    if (!area || !line.startsWith("| ")) continue;
    const [title, verdict, ours] = cells(line);
    if (title === "Capability" || title.startsWith("---")) continue;
    if (SHIPPED.has(verdict)) area.shipped.push(title);
    else if (verdict === "Partial") {
      const missing = /— missing: (.*)$/.exec(ours);
      if (!missing) throw new Error(`docs/153: Partial row "${title}" states no missing part`);
      area.partial.push({ title, missing: missing[1] });
    } else if (verdict === "Gap") area.gaps += 1;
  }
  if (areas.length === 0) throw new Error("docs/153: no areas found in the parity matrix");
  for (const a of areas) {
    a.shipped.sort((x, y) => x.localeCompare(y, "en"));
    a.partial.sort((x, y) => x.title.localeCompare(y.title, "en"));
  }
  return areas;
}

function featuresRegion(areas = parityAreas()) {
  const out = [
    `<!-- Generated by \`${GENERATOR}\` from \`docs/153\` (itself derived from the code by \`tools/opendoc-parity\`). Do not edit; \`webapp/build.sh\` fails when it is stale. -->`,
    "",
  ];
  for (const a of areas) {
    const counts = [`${a.shipped.length} shipped`, `${a.partial.length} partial`, `${a.gaps} not yet`];
    out.push(`<details><summary><strong>${a.title}</strong> — ${counts.join(", ")}</summary>`, "");
    out.push(`**Shipped:** ${a.shipped.join(" · ")}`, "");
    if (a.partial.length) {
      out.push("**Partial** (what is missing):", "");
      for (const p of a.partial) out.push(`- ${p.title} — ${p.missing}`);
      out.push("");
    }
    out.push("</details>", "");
  }
  out.push(
    "The rows not listed here are the ones neither product has, or the ones only ONLYOFFICE has; " +
      "[`docs/153`](docs/153-ONLYOFFICE-CAPABILITY-PARITY-MATRIX.md) ranks the open gaps.",
  );
  return out.join("\n");
}

// --- formats ---------------------------------------------------------------

const IO_DIR = "crates/casual-doc-io/src";

function rustFiles(dir) {
  const out = [];
  for (const entry of readdirSync(join(REPO, dir), { withFileTypes: true })) {
    const path = `${dir}/${entry.name}`;
    if (entry.isDirectory()) out.push(...rustFiles(path));
    else if (entry.name.endsWith(".rs") && entry.name !== "tests.rs") out.push(path);
  }
  return out.sort();
}

/** Every `FormatDescriptor { … }` literal an adapter declares, keyed by the
 *  `formats::` constant it names. */
export function descriptors() {
  const out = new Map();
  for (const file of rustFiles(IO_DIR)) {
    const text = read(file);
    for (const m of text.matchAll(/FormatDescriptor \{([\s\S]*?)\n\s*\}/g)) {
      const body = m[1];
      const id = /FormatId::new\(\s*formats::([A-Z_]+)\s*\)/.exec(body)?.[1];
      if (!id) continue; // a test fixture's descriptor
      const name = /display_name: "([^"]+)"/.exec(body)?.[1];
      const exts = [...(/extensions: vec!\[([^\]]*)\]/.exec(body)?.[1] ?? "").matchAll(/"([^"]+)"/g)].map((x) => x[1]);
      const flag = (k) => {
        const v = new RegExp(`${k}: (true|false)`).exec(body)?.[1];
        if (!v) throw new Error(`${file}: descriptor ${id} does not state ${k}`);
        return v === "true";
      };
      if (out.has(id)) throw new Error(`${file}: a second descriptor for formats::${id}`);
      out.set(id, {
        id,
        file,
        name,
        exts,
        canImport: flag("can_import"),
        canExport: flag("can_export"),
        exact: flag("exact_if_unchanged"),
      });
    }
  }
  if (out.size === 0) throw new Error(`${IO_DIR}: no format descriptors found`);
  return out;
}

/** A claim the generator publishes only while its evidence is in the tree. */
function anchor(file, literal) {
  if (!read(file).includes(literal)) {
    throw new Error(`${GENERATOR}: anchor \`${literal}\` is no longer in ${file}; re-verify the claim it carries and update ANCHORS`);
  }
  return true;
}

/** Per-format notes that are not in a descriptor, each held by its anchors. */
const NOTES = {
  PDF: () => [
    anchor(`${IO_DIR}/pdf_import.rs`, "descriptor.can_import = true") &&
      anchor("webapp/src/pdf_import.mjs", "beginPdfImport") &&
      "Opens as fixed-layout pages (each page a section of page-anchored text boxes, pictures and shapes), through a PDF module the editor loads the first time a PDF is opened (`docs/182`); headless hosts register it with `enable_pdf_import`.",
    anchor("webapp/src/pdf_import.mjs", "openPdfReflow") &&
      "File ▸ Convert to flowing document rebuilds it as paragraphs, headings, lists, tables and columns, as a new document.",
    anchor("crates/casual-doc-wasm-pdf/src/lib.rs", "beginPdfImportWithOcr") &&
      "Scanned pages: text recognition (PaddleOCR on `rten`) runs only when the host names a model manifest (`?pdfOcrModels=`) and the reader agrees to the download.",
    anchor("crates/casual-doc-wasm-pdf/src/lib.rs", "planSave") &&
      anchor(`${IO_DIR}/pdf_preserve.rs`, "pdf.export.preserve_fallback") &&
      "An unedited PDF saves back byte for byte; an edited one is written as an incremental update that keeps the original bytes, falling back to a regenerated PDF where an edit cannot be expressed that way (the save says so).",
    "Export: real, selectable text with embedded subset fonts (`docs/98`).",
  ],
  DOCX: () => ["Unedited files save back byte for byte."],
  RTF: () => ["Opens; there is no RTF writer."],
};

const FORMAT_ORDER = ["DOCX", "DOTX", "ODT", "RTF", "PDF", "HTML", "MARKDOWN", "TEXT", "NORMALIZED_JSON"];

export function formatRows(all = descriptors()) {
  const ids = [...all.keys()];
  const unknown = ids.filter((id) => !FORMAT_ORDER.includes(id));
  if (unknown.length) throw new Error(`${GENERATOR}: new format(s) ${unknown.join(", ")}; add them to FORMAT_ORDER`);
  return FORMAT_ORDER.filter((id) => all.has(id)).map((id) => {
    const d = all.get(id);
    const pdfImport = id === "PDF" && NOTES.PDF()[0];
    return {
      ...d,
      open: d.canImport || !!pdfImport,
      save: d.canExport,
      notes: NOTES[id] ? NOTES[id]().filter(Boolean) : [],
    };
  });
}

const yes = "yes";
const no = "—";

function formatsTable(rows = formatRows()) {
  const out = [
    `<!-- Generated by \`${GENERATOR}\` from the \`FormatDescriptor\` each \`casual-doc-io\` adapter declares, plus anchored PDF-import evidence. Do not edit; \`webapp/build.sh\` fails when it is stale. -->`,
    "",
    "| Format | Extensions | Open | Save / export | Notes |",
    "| --- | --- | :---: | :---: | --- |",
  ];
  for (const r of rows) {
    const exts = r.exts.map((e) => `\`.${e}\``).join(", ");
    out.push(`| ${r.name} | ${exts} | ${r.open ? yes : no} | ${r.save ? yes : no} | ${r.notes.join(" ") || "—"} |`);
  }
  return out.join("\n");
}

// --- agents ---------------------------------------------------------------

export function mcpTools(text = read("tools/opendoc-mcp/src/catalog.rs")) {
  const tools = [];
  for (const m of text.matchAll(/Tool \{\s*name: "([a-z_]+)",\s*title: "([^"]+)",\s*profile: (\w+),\s*read_only: (true|false)/g)) {
    tools.push({ name: m[1], title: m[2], profile: m[3], readOnly: m[4] === "true" });
  }
  if (tools.length === 0) throw new Error("tools/opendoc-mcp/src/catalog.rs: no tools parsed");
  return tools;
}

function agentsRegion() {
  const registry = JSON.parse(read("webapp/generated/commands.json"));
  const commands = registry.commands;
  const families = new Set(commands.map((c) => c.family));
  const by = (v) => commands.filter((c) => c.trackable === v).length;
  const kinds = new Set(commands.map((c) => c.trackable));
  for (const k of kinds) if (!["yes", "no", "not-applicable"].includes(k)) throw new Error(`commands.json: unknown trackable value ${k}`);
  const tools = mcpTools();
  const reads = tools.filter((t) => t.readOnly).map((t) => `\`${t.name}\``);
  const writes = tools.filter((t) => !t.readOnly).map((t) => `\`${t.name}\``);
  return [
    `<!-- Generated by \`${GENERATOR}\` from \`tools/opendoc-mcp/src/catalog.rs\` and \`webapp/generated/commands.json\`. Do not edit; \`webapp/build.sh\` fails when it is stale. -->`,
    "",
    `- **\`opendoc-mcp\`** serves ${tools.length} tools over stdio. Read-only: ${reads.join(", ")}. ` +
      `Changing a session: ${writes.join(", ")}.`,
    `- **The edit vocabulary** (\`casual-doc-command\`, \`docs/181\`): ${commands.length} commands in ${families.size} families, ` +
      `${by("yes")} can land as tracked suggestions, ${by("no")} are refused in suggest mode with a published reason, ` +
      `and ${by("not-applicable")} are not content edits (comments and review decisions). ` +
      "The full table is [`webapp/generated/edit-vocabulary.md`](webapp/generated/edit-vocabulary.md).",
  ].join("\n");
}

// --- viewer package ----------------------------------------------------------

function viewerFormatsRegion() {
  const build = read("packages/opendoc-viewer/build.sh");
  const defaults = /features="\$\{VIEWER_FEATURES:-([^}]+)\}"/.exec(build)?.[1];
  if (!defaults) throw new Error("packages/opendoc-viewer/build.sh: the default VIEWER_FEATURES is not where it was");
  const on = new Set(defaults.split(","));
  const cargo = read("crates/opendoc-viewer/Cargo.toml");
  const declared = new Set([...cargo.matchAll(/^([a-z-]+) = \[/gm)].map((m) => m[1]));
  for (const f of ["formats", "pdf", "pdf-import"]) {
    if (!declared.has(f)) throw new Error(`crates/opendoc-viewer/Cargo.toml: feature \`${f}\` is gone; update ${GENERATOR}`);
  }
  const row = (feature, what) => `| \`${feature}\` | ${what} | ${on.has(feature) ? "yes" : "no"} |`;
  return [
    `<!-- Generated by \`${GENERATOR}\` from \`packages/opendoc-viewer/build.sh\` and \`crates/opendoc-viewer/Cargo.toml\`. Do not edit. -->`,
    "",
    "| Feature | Adds | In this package's default build |",
    "| --- | --- | :---: |",
    "| (always) | DOCX in | yes |",
    row("pdf", "real-text PDF out (`doc.toPdf()`)"),
    row("formats", "ODT, RTF, plain text and normalized JSON in, through the `casual-doc-io` registry (which also links every writer)"),
    row("pdf-import", "PDF in, as fixed-layout pages, with OCR when the host passes a provider (`docs/182`, built for headless hosts); implies `formats`"),
    "",
    `Build another set with \`VIEWER_FEATURES=${[...on, "formats"].join(",")} ./build.sh\`.`,
  ].join("\n");
}

// --- the crate table check ---------------------------------------------------

export function workspaceCrates() {
  const members = [...read("Cargo.toml").matchAll(/^\s*"(crates\/[^"]+|server)",$/gm)].map((m) => m[1]);
  return members.map((dir) => /^name = "([^"]+)"/m.exec(read(`${dir}/Cargo.toml`))[1]).sort();
}

function checkCrateTable(readme) {
  const head = readme.indexOf("| Crate | Responsibility |");
  if (head < 0) throw new Error("README.md: the crate table is missing");
  const named = [];
  for (const line of readme.slice(head).split("\n").slice(2)) {
    if (!line.startsWith("|")) break;
    named.push(/`([^`]+)`/.exec(cells(line)[0])[1]);
  }
  const want = workspaceCrates();
  const missing = want.filter((c) => !named.includes(c));
  const extra = named.filter((c) => !want.includes(c));
  if (missing.length || extra.length) {
    throw new Error(`README.md crate table: missing ${missing.join(", ") || "none"}; not in the workspace ${extra.join(", ") || "none"}`);
  }
}

// --- regions -----------------------------------------------------------------

export const TARGETS = [
  { file: "README.md", regions: { "features": featuresRegion, "formats": formatsTable, "agents": agentsRegion }, after: checkCrateTable },
  { file: "docs/18-SUPPORT-MATRIX.md", regions: { "support-formats": formatsTable } },
  { file: "packages/opendoc-viewer/README.md", regions: { "viewer-formats": viewerFormatsRegion } },
];

export function render(text, regions, file) {
  let result = text;
  for (const [name, make] of Object.entries(regions)) {
    const re = new RegExp(`(<!-- @generated ${name} -->\\n)[\\s\\S]*?(<!-- @end ${name} -->)`);
    if (!re.test(result)) throw new Error(`${file}: region ${name} is missing`);
    const body = make();
    result = result.replace(re, (_, open, close) => `${open}${body}\n${close}`);
  }
  return result;
}

export function build({ check = false } = {}) {
  const stale = [];
  for (const target of TARGETS) {
    const path = join(REPO, target.file);
    const text = readFileSync(path, "utf8");
    const next = render(text, target.regions, target.file);
    target.after?.(next);
    if (next === text) continue;
    if (check) stale.push(target.file);
    else writeFileSync(path, next);
  }
  return stale;
}

if (process.argv[1] && relative(process.argv[1], fileURLToPath(import.meta.url)) === "") {
  const check = process.argv.includes("--check");
  const stale = build({ check });
  if (stale.length) {
    console.error(`stale generated regions in ${stale.join(", ")}; run node ${GENERATOR}`);
    process.exit(1);
  }
  console.log(check ? "README regions are current." : "README regions written.");
}
