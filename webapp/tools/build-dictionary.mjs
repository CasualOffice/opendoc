#!/usr/bin/env node
// Generates `webapp/dict/*.txt` from a SCOWL release tarball.
//
// The word lists this editor spell-checks against are a DERIVED artifact, and
// SKILL.md §8 is explicit that a derived number or file is generated from a
// committed generator or it is not published. So this script is committed next
// to its output, it is deterministic, and re-running it on the same release
// must reproduce the committed files BYTE FOR BYTE — `dictionary_artifact`
// (tests/dictionary_artifact.test.mjs) re-derives the shape and the invariants
// that do not need the 2.5 MB tarball, and `--check` here does the rest when a
// release is at hand.
//
// Usage:
//   node tools/build-dictionary.mjs --scowl <dir containing SCOWL's final/>
//   node tools/build-dictionary.mjs --scowl <dir> --check   (verify, write nothing)
//
// ## Why SCOWL, and why the pre-expanded lists
//
// docs/114 §2 settles this and the reasoning is not repeated here, but the two
// load-bearing points are:
//
//   * `webapp/package.json` has ZERO runtime dependencies, so a Hunspell engine
//     in JS is not available to us, and a `.dic`+`.aff` pair without an affix
//     expander is unusable. SCOWL's `final/` holds already-inflected plain word
//     lists, which is exactly what a `Set` membership test wants.
//   * SCOWL's licence is attribution-only and names "the output created from
//     the scripts" explicitly, so a generated list is Apache-2.0 compatible.
//     The notice ships verbatim as `webapp/dict/LICENSE.SCOWL.txt`.
//
// ## Provenance — re-measure, do not trust this comment
//
//   release : scowl-2020.12.07
//   url     : https://downloads.sourceforge.net/wordlist/scowl-2020.12.07.tar.gz
//   bytes   : 2569810
//   sha256  : 5587667caa20c4891390c2d42dbb4d5c4c3f41bee77af1457ece3ba23fb859cc
//
// Verify with `shasum -a 256 scowl-2020.12.07.tar.gz`. The upstream git tree
// does NOT contain `final/` — those files are generated by SCOWL's Makefile —
// so the release tarball is the artifact, not the checkout.

import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

/** SCOWL release this generator is pinned to. */
export const SCOWL_RELEASE = "scowl-2020.12.07";
export const SCOWL_URL =
  "https://downloads.sourceforge.net/wordlist/scowl-2020.12.07.tar.gz";
export const SCOWL_TARBALL_BYTES = 2_569_810;
export const SCOWL_TARBALL_SHA256 =
  "5587667caa20c4891390c2d42dbb4d5c4c3f41bee77af1457ece3ba23fb859cc";

/** The SCOWL size level the dictionary is cut at.
 *
 *  60 is the level the official Hunspell `en_US` dictionary uses, so it is the
 *  tier that has been shipped and error-checked for twenty years. Level 70 adds
 *  words that are *more likely to be misspellings of common words* — SCOWL's own
 *  README names `ort` and `calender` — which trades false positives for false
 *  negatives and makes the product worse. */
export const LEVEL = 60;

/** The tier that ranks a suggestion as "common" (docs/114 §5.4). It is what
 *  makes `teh` suggest `the` rather than `ten`. */
export const COMMON_LEVEL = 35;

/** Separates the common tier from the rest inside a dictionary file. A line of
 *  exactly this, so the parse is one `indexOf` and two `split`s and the file
 *  stays sorted, reviewable and diffable on both sides of it. */
export const SECTION_SEPARATOR = "---";

/** `(dialect, kind)` pairs per language, per docs/114 §2.3.
 *
 *  `-abbreviations` is deliberately excluded: the list is dominated by
 *  ambiguous two- and three-letter forms that make real misspellings pass. */
export const LANGUAGE_SETS = {
  "en-US": [
    ["english", "words"],
    ["english", "upper"],
    ["english", "contractions"],
    ["english", "proper-names"],
    ["american", "words"],
    ["american", "upper"],
    ["american", "proper-names"],
  ],
  "en-GB": [
    ["english", "words"],
    ["english", "upper"],
    ["english", "contractions"],
    ["english", "proper-names"],
    ["british", "words"],
    ["british", "upper"],
    ["british", "proper-names"],
    ["british_z", "words"],
    ["british_z", "upper"],
  ],
};

/**
 * Whether a raw SCOWL entry belongs in the shipped list.
 *
 * Exported so `dictionary_artifact.test.mjs` can assert each rule independently
 * of the tarball — every filter here removes entries a checker would otherwise
 * be asked about, and a silently relaxed filter is how a word list grows junk.
 */
export function keepEntry(word) {
  // Possessives are handled BY RULE at check time (docs/114 §5.3 strips a
  // trailing `'s` / `’s` and re-checks the stem), so ~15,000 of them in the
  // file would be dead weight that every fetch pays for.
  if (/['’]s$/.test(word)) return false;
  // SCOWL marks a handful of entries it is unsure about; they are not words.
  if (word.includes("/") || word.includes(" ")) return false;
  if (word.length === 0) return false;
  return true;
}

/** Codepoint order — deliberately NOT `localeCompare`, whose result depends on
 *  the machine's ICU data and would make the artifact non-reproducible. */
export function sortWords(words) {
  return [...words].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

/**
 * Assembles one language's two tiers from an extracted SCOWL `final/`.
 *
 * Returns `{ common, rest }`, both sorted and disjoint: a word in the common
 * tier is never repeated below the separator, so the file has no duplicates and
 * `common.size + rest.size` is the dictionary's word count.
 */
export function collectLanguage(finalDir, language) {
  const pairs = LANGUAGE_SETS[language];
  if (!pairs) throw new Error(`no file set defined for ${language}`);
  const available = new Set(readdirSync(finalDir));
  const common = new Set();
  const all = new Set();
  for (const [dialect, kind] of pairs) {
    for (const name of available) {
      const match = name.match(/^(.*)-([a-z-]+)\.(\d+)$/);
      if (!match) continue;
      const [, fileDialect, fileKind, levelText] = match;
      if (fileDialect !== dialect || fileKind !== kind) continue;
      const level = Number(levelText);
      if (level > LEVEL) continue;
      // SCOWL's `final/` files are ISO-8859-1 (`file(1)` says "ISO-8859 text").
      // Decoding them as UTF-8 would mangle every accented entry into U+FFFD,
      // which is both wrong and non-reproducible across Node versions.
      const text = new TextDecoder("iso-8859-1").decode(
        readFileSync(join(finalDir, name)),
      );
      for (const raw of text.split("\n")) {
        const word = raw.trim();
        if (!keepEntry(word)) continue;
        all.add(word);
        if (level <= COMMON_LEVEL) common.add(word);
      }
    }
  }
  const rest = new Set([...all].filter((word) => !common.has(word)));
  return { common: sortWords(common), rest: sortWords(rest) };
}

/** The exact bytes of a dictionary file. One trailing newline, no BOM, no
 *  header — a header would have to be skipped by every parser and would invite
 *  a hand edit. Provenance lives in this generator and in `dict/README.md`. */
export function renderDictionary({ common, rest }) {
  return `${common.join("\n")}\n${SECTION_SEPARATOR}\n${rest.join("\n")}\n`;
}

function sha256(text) {
  return createHash("sha256").update(text, "utf8").digest("hex");
}

function main(argv) {
  const scowlIndex = argv.indexOf("--scowl");
  if (scowlIndex < 0 || !argv[scowlIndex + 1]) {
    console.error(
      "usage: node tools/build-dictionary.mjs --scowl <dir containing final/> [--check]",
    );
    process.exitCode = 2;
    return;
  }
  const root = argv[scowlIndex + 1];
  const finalDir = readdirSync(root).includes("final") ? join(root, "final") : root;
  const check = argv.includes("--check");
  const outDir = new URL("../dict/", import.meta.url);
  mkdirSync(outDir, { recursive: true });

  let failed = false;
  for (const language of Object.keys(LANGUAGE_SETS)) {
    const tiers = collectLanguage(finalDir, language);
    const text = renderDictionary(tiers);
    const target = new URL(`${language}.txt`, outDir);
    const words = tiers.common.length + tiers.rest.length;
    const summary =
      `${language}: ${words} words (${tiers.common.length} common), ` +
      `${Buffer.byteLength(text, "utf8")} B, sha256 ${sha256(text).slice(0, 16)}…`;
    if (check) {
      let existing = "";
      try {
        existing = readFileSync(target, "utf8");
      } catch {
        existing = "";
      }
      if (existing === text) {
        console.log(`ok   ${summary}`);
      } else {
        failed = true;
        console.error(`DIFF ${summary} — committed file does not match this release`);
      }
    } else {
      writeFileSync(target, text);
      console.log(`wrote ${summary}`);
    }
  }
  if (failed) process.exitCode = 1;
}

// Importable for the artifact test; runnable as a script.
if (process.argv[1] && import.meta.url.endsWith(process.argv[1].replace(/^.*\//, ""))) {
  main(process.argv.slice(2));
}
