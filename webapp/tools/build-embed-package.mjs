#!/usr/bin/env node
// Generates `packages/opendoc-embed`'s source and typings from `webapp/src`.
//
// ONE rule, so there is never a question which copy is real: `webapp/src` is
// the authority and everything under `packages/opendoc-embed/src` is generated
// from it. npm cannot publish a file from outside the package directory —
// `files` has no way to reach `../../webapp/src` — and the editor page, the demo
// host page and the specs all have to import the same modules the package
// ships, or "the package resolves the same capabilities the editor does" is a
// hope rather than a fact. A copy somebody can edit is a copy that drifts, so
// this tool writes them and `--check` fails the build when the committed files
// are not what a fresh run produces. Same shape as `build-site.py --check` for
// the static pages and `build-locale.mjs` for the English catalogue.
//
// The typings are DERIVED from the tables rather than typed out beside them.
// A hand-written `"preview" | "readonly" | ...` union is a second copy of the
// role list that compiles happily while being wrong — which is the exact defect
// `SKILL.md` §8 records about hand-maintained counts, in TypeScript's clothing.
// So this imports the authority and emits the unions from its real values.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { CAPABILITIES, LEGACY_PRESETS, PRESET_NAMES, ROLES } from "../src/capabilities.mjs";
import { REGIONS } from "../src/capabilities.mjs";
import { HOST_EVENTS, REFUSAL_CODES, REQUIREMENTS } from "../src/host_contract.mjs";

const WEBAPP = join(dirname(fileURLToPath(import.meta.url)), "..");
const REPO = join(WEBAPP, "..");
const PACKAGE = join(REPO, "packages", "opendoc-embed");
/** Generated package path → the `webapp/src` module it is generated from. The
 *  names match on both sides on purpose: a rename table is one more thing that
 *  can be wrong. */
const COPIES = Object.freeze({
  "capabilities.mjs": "capabilities.mjs",
  "embed_element.mjs": "embed_element.mjs",
  "embed_define.js": "embed_define.js",
  // `docs/126` phase 2. A host across an origin boundary cannot reach
  // `window.opendoc`, so the `postMessage` client is the only transport they have
  // — and it is useless without the schema, because its verbs, its events and its
  // envelope all come from there. Shipping one without the other would publish a
  // client a host cannot use.
  "host_contract.mjs": "host_contract.mjs",
  "host_client.mjs": "host_client.mjs",
});

/** A TypeScript union of string literals, or `never` for an empty list. */
function union(values) {
  return values.length ? values.map((v) => JSON.stringify(v)).join(" | ") : "never";
}

/** One generated module: its authority, verbatim, under a banner saying where it
 *  came from. Verbatim matters — a transformed copy is a second implementation,
 *  and then the package and the editor can disagree about what `readonly`
 *  means. */
function copiedModule(name) {
  const from = join(WEBAPP, "src", COPIES[name]);
  const source = readFileSync(from, "utf8");
  return (
    `// GENERATED by webapp/tools/build-embed-package.mjs — do not edit.\n` +
    `// Source of truth: ${relative(REPO, from)}\n` +
    `//\n` +
    `// Edit the source and re-run the tool. \`embed_package.test.mjs\` fails if\n` +
    `// this file is not byte-identical to a fresh generation, so a hand edit here\n` +
    `// is a build failure rather than a divergence nobody notices.\n` +
    `\n` +
    source
  );
}

/** The generated typings. The literal unions come from the authority's real
 *  exported values; the element's shape is declared here because it has no other
 *  home, and `embed_package.test.mjs` checks every member it names against the
 *  class it describes so the two cannot drift either. */
function typings() {
  const aliases = Object.entries(LEGACY_PRESETS)
    .map(([legacy, role]) => `  ${legacy}: ${role === null ? "null" : JSON.stringify(role)};`)
    .join("\n");
  return `// GENERATED by webapp/tools/build-embed-package.mjs — do not edit.
//
// The unions below are emitted from the real exported values of
// webapp/src/capabilities.mjs, so a role or capability can never exist in the
// types without existing in the code, or the other way round.

/** Everything a host can grant or withhold. */
export type Capability = ${union([...CAPABILITIES])};

/** The five roles, in strictly increasing order of what they grant. */
export type Role = ${union([...ROLES])};

/** Every name \`mode\` accepts: the roles plus the legacy preset names. */
export type Mode = ${union([...PRESET_NAMES])};

/** Which of the editor's three review modes a capability set means. */
export type EditingMode = "editing" | "suggesting" | "viewing";

export declare const CAPABILITIES: readonly Capability[];
export declare const ROLES: readonly Role[];
export declare const PRESET_NAMES: readonly Mode[];
export declare const LEGACY_PRESETS: {
${aliases}
};

export declare const DEFAULT_EDITOR_SRC: string;
export declare const OPENDOC_EDITOR_TAG: "opendoc-editor";
export declare const CAPABILITIES_EVENT: "opendoc-capabilities";

/**
 * Resolves the capability set for a page load.
 *
 * With no \`mode\`, \`framed\` decides: a page that is not the top window was put
 * there by someone else, and the safe reading of that is the embedded preset.
 * An unrecognised \`mode\` falls back to that same default, never to more.
 */
export declare function resolveCapabilities(input?: {
  mode?: Mode | string | null;
  framed?: boolean;
  autosave?: boolean | null;
  /** Narrows the preset, never widens it. \`"-print,-download"\` or
   *  \`"print,download"\`; an unknown entry is dropped, and dropping narrows
   *  nothing, so a typo can never grant more. */
  withhold?: string | null;
}): Set<Capability>;

// ---- Region composition (\`docs/126\` phase 3) -------------------------------
//
// A different axis from the capability set, and deliberately not folded into it:
// a withheld REGION is a presentation decision about the host's own page, and a
// withheld CAPABILITY is a permission. "Never, for you" is composition and is
// silent; "not right now" is state and explains itself with a reason.

/** Every region of the chrome a host can withhold. */
export type Region = ${union([...REGIONS])};

export declare const REGIONS: readonly Region[];

/**
 * The chrome regions a page load gets.
 *
 * Presets, by role: \`preview\` gets none of them — it is the runtime as a layout
 * and rendering engine, a picture of the document — and \`readonly\` gets READING
 * chrome: the menu bar rather than the ribbon, the navigation rail, the status bar
 * with its page count and zoom, and the find card. Every other role gets all of
 * them. Withholding \`ribbon\` withholds its bands too.
 */
export declare function resolveRegions(input?: {
  mode?: Mode | string | null;
  framed?: boolean;
  withhold?: string | null;
}): Set<Region>;

/** Reads \`mode\` and \`chrome\` off a real window. */
export declare function hostRegions(view?: unknown): Set<Region>;

/** Every host input carried on the page's URL, read once. */
export declare function hostConfig(view?: unknown): {
  mode: string | null;
  autosave: boolean | null;
  withhold: string | null;
  chrome: string | null;
  framed: boolean;
};

/** Parses a withhold list against a vocabulary. Only ever narrows. */
export declare function parseWithheld(raw: string | null | undefined, known: readonly string[]): readonly string[];

/** Maps a capability set onto the editor's existing three review modes. Fails
 *  closed to \`"viewing"\` for anything that is not a set. */
export declare function editingModeFor(capabilities: unknown): EditingMode;

/** The iframe \`sandbox\` tokens an embedding host should give a capability set. */
export declare function sandboxTokensFor(capabilities: unknown): readonly string[];

/** Reads \`mode\`, \`autosave\` and the framing off a real window. */
export declare function hostCapabilities(view?: unknown): Set<Capability>;

/** Detail carried by the \`${"opendoc-capabilities"}\` event, fired once per mount. */
export interface OpenDocCapabilitiesDetail {
  mode: string | null;
  capabilities: readonly Capability[];
  editingMode: EditingMode;
  sandbox: readonly string[];
  src: string;
}

/** An embedded opendoc editor.
 *
 *  \`mode\` is not called \`role\`: \`role\` is a global ARIA attribute, and
 *  \`role="readonly"\` would publish an invalid ARIA role to every assistive
 *  technology on the page.
 *
 *  Setting \`mode\` or \`editor-src\` after mount REMOUNTS. A permission handed
 *  over after the document is on screen was never a permission. */
export declare class OpenDocEditorElement extends HTMLElement {
  mode: string | null;
  readonly capabilities: readonly Capability[];
  readonly editingMode: EditingMode;
  readonly sandbox: readonly string[];
  readonly frame: HTMLIFrameElement | null;
  can(capability: Capability | string): boolean;
}

/** Registers the element. Idempotent, and returns whether this call was the one
 *  that registered it. */
export declare function defineOpenDocEditor(tag?: string): boolean;

// ---- The host contract (\`docs/126\` phase 2) --------------------------------
//
// The unions below are emitted from the real exported values of
// webapp/src/host_contract.mjs, for the same reason the capability unions are: a
// hand-written literal union is a second copy of the table that compiles happily
// while being wrong.

/** Every event a host can hear. */
export type HostEventName = ${union(HOST_EVENTS.map((event) => event.name))};

/** Everything a refusal can say, as a code to branch on — never the message,
 *  which is localised and belongs to the chrome. */
export type RefusalCode = ${union([...REFUSAL_CODES])};

/** What a command can require of the host's grant. \`mutate\` is not a capability:
 *  it asks whether this page may change the document at all, which is granted by
 *  \`edit\` OR by \`comment\` (a commentor's changes are tracked suggestions). */
export type Requirement = ${union([...REQUIREMENTS])};

export declare const CONTRACT_VERSION: number;
export declare const HOST_EVENT_NAMES: readonly HostEventName[];
export declare const REFUSAL_CODES: readonly RefusalCode[];
export declare const REQUIREMENTS: readonly Requirement[];

export interface Refusal {
  code: RefusalCode;
  command: string | null;
  requires: Requirement | null;
  /** Already localised, and for a person to read. Do not branch on it. */
  message: string;
}

export interface CommandResult {
  ok: boolean;
  command: string;
  /** The engine's revision watermark, or null when it could not be read. */
  revision: number | null;
  refusal?: Refusal;
}

export interface CommandState {
  id: string;
  /** In the contract at all. */
  known: boolean;
  /** In the registry right now — the table commands exist only with a caret in a
   *  table. Distinct from \`granted\`, which is about permission. */
  present: boolean;
  requires: Requirement | null;
  granted: boolean;
  available: boolean;
  /** The chrome's own reason when it is unavailable. */
  reason: string;
}

export interface HostEvent<Detail = Record<string, unknown>> {
  event: HostEventName;
  detail: Detail;
}

/** The editor, as a host addresses it. Both transports expose this. */
export interface OpenDocHostSession {
  describe(): Promise<unknown> | unknown;
  execute(id: string, args?: readonly unknown[]): Promise<CommandResult>;
  query(id: string): Promise<CommandState> | CommandState;
  ping(): Promise<unknown> | unknown;
  on(event: HostEventName, listener: (event: HostEvent) => void): () => void;
  off(event: HostEventName, listener: (event: HostEvent) => void): void;
}

/**
 * A client for an embedded editor, over \`postMessage\`.
 *
 * \`editorOrigin\` is REQUIRED and may not be \`"*"\`: the only default that would
 * always work is a wildcard, and posting document content to a wildcard target is
 * a decision no library should make for a host.
 */
export declare function createHostClient(io: {
  frame: HTMLIFrameElement | Window;
  editorOrigin: string;
  view?: Window;
  timeout?: number;
}): OpenDocHostSession & { dispose(): void; inFlight(): number };

/** Whether a capability set may run a command with this requirement. */
export declare function grantsRequirement(
  requires: Requirement | null,
  capabilities: unknown,
): boolean;

/** The contract row for a command id, or null when it is outside the contract. */
export declare function commandContract(
  id: string,
): { id: string; requires: Requirement | null; args: readonly object[]; family?: string } | null;

declare global {
  interface HTMLElementTagNameMap {
    "opendoc-editor": OpenDocEditorElement;
  }
  interface HTMLElementEventMap {
    "opendoc-capabilities": CustomEvent<OpenDocCapabilitiesDetail>;
  }
}
`;
}

/** Every generated path and what belongs in it. */
function artifacts() {
  return [
    ...Object.keys(COPIES).map((name) => [join(PACKAGE, "src", name), copiedModule(name)]),
    [join(PACKAGE, "types", "index.d.ts"), typings()],
  ];
}

function main() {
  const check = process.argv.includes("--check");
  const stale = [];
  for (const [path, content] of artifacts()) {
    let current = null;
    try {
      current = readFileSync(path, "utf8");
    } catch {
      current = null;
    }
    if (current === content) continue;
    if (check) {
      stale.push(relative(REPO, path));
      continue;
    }
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    console.log(`build-embed-package: wrote ${relative(REPO, path)}`);
  }
  if (check && stale.length) {
    console.error(
      `build-embed-package --check: ${stale.length} generated file(s) are stale:\n` +
        stale.map((p) => `  ${p}`).join("\n") +
        "\nRun `node webapp/tools/build-embed-package.mjs` and commit the result.",
    );
    process.exit(1);
  }
  if (check) console.log(`build-embed-package --check: ${artifacts().length} file(s) up to date.`);
}

main();
