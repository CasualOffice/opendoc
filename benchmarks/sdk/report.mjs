#!/usr/bin/env node
// Renders benchmarks/sdk/results.json into the generated region of
// docs/176 section 12.10. No number in that region is typed (SKILL section 9):
//
//   node benchmarks/sdk/report.mjs           rewrite the region
//   node benchmarks/sdk/report.mjs --check   fail if the region is stale
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "..", "..");
export const DOC = join(repo, "docs", "176-THREE-SDK-PRODUCTS.md");
export const RESULTS = join(here, "results.json");
const BEGIN = "<!-- sdk-bench:begin (generated by benchmarks/sdk/report.mjs from benchmarks/sdk/results.json; do not edit) -->";
const END = "<!-- sdk-bench:end -->";

const ms = (cell) => (cell && !cell.error && cell.ms != null ? `${cell.ms} ms` : cell?.error ? "failed" : "—");
const mb = (cell) => (cell && !cell.error && cell.peakMB != null ? `${cell.peakMB} MB` : "—");

function ratio(ours, theirs) {
  if (!ours?.ms || !theirs?.ms) return "—";
  const r = theirs.ms / ours.ms;
  return r >= 1 ? `${r.toFixed(1)}× faster` : `${(1 / r).toFixed(1)}× slower`;
}

const COMPETITOR = {
  generate: "docx-js",
  template: "docxtemplater",
  html: "mammoth",
  text: "mammoth",
  pdf: "libreoffice",
  "py-generate": "python-docx",
  "py-read": "python-docx",
  "java-generate": "poi",
  "java-read": "poi",
};
const TASK = {
  generate: "Generate DOCX (the same docx-js program)",
  template: "Fill a template (the same template and data)",
  html: "DOCX to HTML",
  text: "DOCX to plain text",
  pdf: "DOCX to PDF",
  "py-generate": "Generate DOCX (the same python-docx program)",
  "py-read": "Open and read every paragraph (Python)",
  "java-generate": "Generate DOCX (Java, POI-style calls)",
  "java-read": "Open and read every paragraph (Java)",
};

export function render(results) {
  const v = results.versions;
  const env = results.environment;
  const out = [BEGIN, ""];
  out.push(
    `Measured on ${env.platform}, ${env.cpu} (${env.cores} cores, ${env.memoryGB} GB), Node ${env.node}; median of ${env.iterations} runs after a warm-up, each library and task in its own process. ` +
      `Versions: opendoc ${v.opendoc}, docx ${v.docx}, docxtemplater ${v.docxtemplater}, mammoth ${v.mammoth}` +
      `${v.libreoffice ? `, ${v.libreoffice}` : ""}${v["python-docx"] ? `, python-docx ${v["python-docx"]}` : ""}.`,
  );
  out.push("", "| Task | Input | OpenDoc | Competitor | OpenDoc speed | OpenDoc peak RSS | Competitor peak RSS |", "| --- | --- | ---: | ---: | --- | ---: | ---: |");
  for (const row of results.speed) {
    const name = COMPETITOR[row.task];
    const theirs = row[name];
    out.push(
      `| ${TASK[row.task]} | ${row.input} | ${ms(row.opendoc)} | ${name}: ${ms(theirs)} | ${ratio(row.opendoc, theirs)} | ${mb(row.opendoc)} | ${mb(theirs)} |`,
    );
  }
  out.push("", "**Round trip** (open, save, reopen; `kept` is input package parts present in the output, `text` whether the body text survived, `losses` OpenDoc's own report):", "");
  const hasPy = results.roundTrip.some((r) => r["python-docx"]);
  out.push(
    `| Fixture | Parts | OpenDoc preserve: kept / text / losses | OpenDoc semantic: kept / text / losses${hasPy ? " | python-docx: kept / text" : ""} |`,
    `| --- | ---: | --- | ---${hasPy ? " | ---" : ""} |`,
  );
  const side = (s) => (s?.error ? "failed" : `${s.partsKept} / ${s.textSame ? "same" : "changed"}${s.losses == null ? "" : ` / ${s.losses}`}`);
  for (const row of results.roundTrip) {
    out.push(
      `| ${row.fixture} | ${row.parts} | ${side(row.opendoc.preserve)} | ${side(row.opendoc.semantic)}${hasPy ? ` | ${row["python-docx"] ? side(row["python-docx"]) : "—"}` : ""} |`,
    );
  }
  const lo = results.fidelity.some((r) => r.libreofficePages != null);
  out.push("", `**Pages** (OpenDoc's layout${lo ? " against LibreOffice's" : ""}):`, "");
  out.push(`| Fixture | OpenDoc pages${lo ? " | LibreOffice pages" : ""} |`, `| --- | ---:${lo ? " | ---:" : ""} |`);
  for (const row of results.fidelity) {
    out.push(`| ${row.fixture} | ${row.opendocPages}${lo ? ` | ${row.libreofficePages ?? "—"}` : ""} |`);
  }
  out.push("");
  for (const note of results.notes) out.push(`- ${note}`);
  out.push("", END);
  return out.join("\n");
}

export function apply(doc, results) {
  const start = doc.indexOf(BEGIN);
  const end = doc.indexOf(END);
  if (start < 0 || end < start) throw new Error(`${DOC}: the sdk-bench region is missing`);
  return doc.slice(0, start) + render(results) + doc.slice(end + END.length);
}

if (process.argv[1] && relative(process.argv[1], fileURLToPath(import.meta.url)) === "") {
  const doc = readFileSync(DOC, "utf8");
  const next = apply(doc, JSON.parse(readFileSync(RESULTS, "utf8")));
  if (process.argv.includes("--check")) {
    if (next !== doc) {
      console.error("docs/176 section 12.10 is stale; run node benchmarks/sdk/report.mjs");
      process.exit(1);
    }
    console.log("docs/176 section 12.10 matches results.json.");
  } else {
    writeFileSync(DOC, next);
    console.log("docs/176 section 12.10 written.");
  }
}
