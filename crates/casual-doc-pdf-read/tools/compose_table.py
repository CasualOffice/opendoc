"""Writes `src/compose_table.rs`: the canonical compositions (NFC's
"primary composites") of one base character and one combining mark, both in
the Basic Multilingual Plane, from the Unicode Character Database that ships
with Python (`unicodedata`).

    python3 crates/casual-doc-pdf-read/tools/compose_table.py          # write
    python3 crates/casual-doc-pdf-read/tools/compose_table.py --check  # compare

The table is sorted by (base, mark) so `unicode::compose_pair` is a binary
search. Composition exclusions are left out, as NFC leaves them out: a pair
is kept only when NFC of the two characters is the one precomposed character.
"""
import pathlib
import sys
import unicodedata

OUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "compose_table.rs"


def pairs():
    out = []
    for code in range(0x00C0, 0x10000):
        c = chr(code)
        decomposition = unicodedata.decomposition(c)
        if not decomposition or decomposition.startswith("<"):
            continue
        parts = [int(p, 16) for p in decomposition.split()]
        if len(parts) != 2:
            continue
        base, mark = parts
        if unicodedata.combining(chr(mark)) == 0 and unicodedata.category(chr(mark)) != "Mn":
            continue
        if unicodedata.normalize("NFC", chr(base) + chr(mark)) != c:
            continue
        out.append((base, mark, code))
    out.sort()
    return out


def render():
    rows = pairs()
    lines = [
        "// SPDX-License-Identifier: Apache-2.0",
        "",
        "// @generated by tools/compose_table.py from Python's unicodedata",
        f"// (Unicode {unicodedata.unidata_version}). Do not edit by hand.",
        "",
        "/// (base, combining mark, precomposed), sorted by (base, mark).",
        f"pub(crate) const COMPOSE: [(u16, u16, u16); {len(rows)}] = [",
    ]
    for base, mark, code in rows:
        lines.append(f"    (0x{base:04X}, 0x{mark:04X}, 0x{code:04X}),")
    lines.append("];")
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            sys.exit(f"{OUT} is stale: run {__file__}")
        return
    OUT.write_text(text)


if __name__ == "__main__":
    main()
