#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn wingdings2_empty_checkbox_maps_to_a_box() {
        // The Medical form's empty checkbox: `w:sym w:font="Wingdings 2"
        // w:char="F0A3"` must render as a visible empty box, never be dropped.
        let glyph = resolve_symbol("Wingdings 2", 0xF0A3);
        assert!(matches!(glyph, '\u{25A1}' | '\u{2610}'), "got {glyph:?}");
        assert_eq!(map_symbol("Wingdings 2", 0xF0A3), Some(glyph));
    }

    #[test]
    fn wingdings2_checked_and_crossed_boxes() {
        assert_eq!(map_symbol("Wingdings 2", 0xF052), Some('\u{2611}')); // ☑
        assert_eq!(map_symbol("Wingdings 2", 0xF053), Some('\u{2612}')); // ☒ (from 2BBD)
    }

    #[test]
    fn symbol_font_greek_math_arrow_bullet_and_suit() {
        assert_eq!(map_symbol("Symbol", 0xF0B7), Some('•')); // bullet
        assert_eq!(map_symbol("Symbol", 0xF062), Some('β')); // greek small beta
        assert_eq!(map_symbol("Symbol", 0xF044), Some('Δ')); // greek capital delta
        assert_eq!(map_symbol("Symbol", 0xF0A5), Some('∞')); // infinity
        assert_eq!(map_symbol("Symbol", 0xF0AE), Some('→')); // rightwards arrow
        assert_eq!(map_symbol("Symbol", 0xF0A8), Some('♦')); // black diamond suit
    }

    #[test]
    fn wingdings_check_cross_circle_and_square() {
        assert_eq!(map_symbol("Wingdings", 0xF0FC), Some('✓')); // check mark
        assert_eq!(map_symbol("Wingdings", 0xF0FE), Some('☑')); // checked box (from 1F5F9)
        assert_eq!(map_symbol("Wingdings", 0xF0FB), Some('✗')); // ballot X (from 1F5F6)
        assert_eq!(map_symbol("Wingdings", 0xF06C), Some('●')); // filled circle (from 26AB)
    }

    #[test]
    fn wingdings3_arrow_folds_to_bmp() {
        // A Wingdings 3 triangle-headed rightwards arrow (byte 0x22 → U+2B62)
        // folds to the covered BMP rightwards arrow.
        assert_eq!(map_symbol("Wingdings 3", 0xF022), Some('→'));
    }

    #[test]
    fn webdings_maps_and_stays_in_bmp_or_astral_but_never_pua_fragment() {
        // Every Webdings glyph resolves to some renderable char (no PUA fragments).
        for byte in 0x20u32..=0xFF {
            if let Some(c) = map_symbol("Webdings", 0xF000 + byte) {
                assert!(!is_private_use(c as u32), "byte {byte:#X} -> PUA {c:?}");
            }
        }
    }

    #[test]
    fn code_accepted_with_or_without_pua_offset() {
        assert_eq!(map_symbol("Wingdings 2", 0x52), Some('☑'));
        assert_eq!(map_symbol("Wingdings 2", 0xF052), Some('☑'));
    }

    #[test]
    fn ordinary_font_is_never_reinterpreted() {
        assert_eq!(map_symbol("Calibri", u32::from('l')), None);
        assert_eq!(map_symbol("Arial", 0xF06C), None);
    }

    #[test]
    fn unmapped_pua_falls_back_to_visible_placeholder_not_dropped() {
        // A code outside every table (unrecognized face) with a non-ASCII byte →
        // visible □, never nothing.
        let glyph = resolve_symbol("NotAFont", 0xF0EE);
        assert_eq!(glyph, '\u{25A1}');
        assert_ne!(glyph, '\0');
    }

    #[test]
    fn unmapped_ascii_alias_recovers_the_letter() {
        assert_eq!(resolve_symbol("NotAFont", 0xF041), 'A');
    }

    #[test]
    fn no_table_entry_resolves_to_a_private_use_glyph() {
        // The coverage layer must never leave a glyph-fragment PUA target exposed.
        for (font, table) in [
            ("Symbol", SYMBOL),
            ("Wingdings", WINGDINGS),
            ("Wingdings 2", WINGDINGS2),
            ("Wingdings 3", WINGDINGS3),
            ("Webdings", WEBDINGS),
        ] {
            for &(byte, _) in table {
                let c = map_symbol(font, 0xF000 + u32::from(byte)).unwrap();
                assert!(!is_private_use(c as u32), "{font} {byte:#X} -> PUA {c:?}");
            }
        }
    }
}
