//! Legacy symbol-font code point → Unicode mapping.
//!
//! Word encodes a `w:sym` glyph as a *(font, char)* pair where the character is a
//! byte position in a legacy symbol font (Wingdings, Wingdings 2/3, Symbol,
//! Webdings), usually offset into the Unicode Private Use Area
//! (`0xF020..=0xF0FF`). Those fonts are not bundled, so the raw code point cannot
//! be drawn by a normal text face — it would render as tofu or, worse, be dropped
//! entirely.
//!
//! This module maps the full published character set of each face to its Unicode
//! equivalent so a bundled/OS text face (DejaVu, Liberation, or a system font) can
//! draw it. The per-face tables (`SYMBOL`, `WINGDINGS`, …) are transcribed
//! verbatim from the published dingbat→Unicode mapping; a separate
//! `coverage_fallback` then folds the code points Unicode assigned in
//! poorly-covered blocks (the Unicode-7 dingbats `U+1F5xx`/`U+1F7xx`, the
//! Miscellaneous-Symbols-and-Arrows block `U+2Bxx`, glyph-fragment PUA) down to
//! the well-covered BMP glyph that reads the same (e.g. `U+1F5F9` → `☑` U+2611,
//! `U+26AB` → `●` U+25CF), because coverage is what makes the glyph actually
//! appear. The long tail of genuinely pictographic glyphs (weather, vehicles,
//! faces) keeps its true code point, rendering on a capable system font and
//! degrading to a visible `.notdef`/placeholder box otherwise — never nothing.
//!
//! Source data: the `mwilliamson/dingbat-to-unicode` compilation of the
//! Microsoft/Unicode dingbat mappings, cross-checked against the authoritative
//! Adobe `Symbol` mapping (`unicode.org` `MAPPINGS/VENDORS/ADOBE/symbol.txt`).

/// The recognized legacy symbol font families.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
enum Family {
    /// Adobe `Symbol` (Greek + math + arrows + card suits).
    Symbol,
    /// `Wingdings` (bullets, boxes, checks, hands, stars, arrows).
    Wingdings,
    /// `Wingdings 2` (checkboxes, hands, geometric shapes, stars).
    Wingdings2,
    /// `Wingdings 3` (arrows and triangles).
    Wingdings3,
    /// `Webdings` (pictographs; Unicode equivalents where they exist).
    Webdings,
}

/// Classifies a declared font family as a known legacy symbol face, or `None`
/// when it is an ordinary text font (whose characters must not be reinterpreted).
/// Matching is case-insensitive and ignores surrounding whitespace.
fn classify(font: &str) -> Option<Family> {
    let font = font.trim();
    if font.eq_ignore_ascii_case("Symbol") {
        Some(Family::Symbol)
    } else if font.eq_ignore_ascii_case("Wingdings") {
        Some(Family::Wingdings)
    } else if font.eq_ignore_ascii_case("Wingdings 2") {
        Some(Family::Wingdings2)
    } else if font.eq_ignore_ascii_case("Wingdings 3") {
        Some(Family::Wingdings3)
    } else if font.eq_ignore_ascii_case("Webdings") {
        Some(Family::Webdings)
    } else {
        None
    }
}

/// Recovers the font's own byte position (`0x20..=0xFF`) from a `w:sym` code
/// point, stripping the Private-Use-Area offset (`0xF000`) when present. Returns
/// `None` for anything outside a legacy symbol font's byte range.
fn normalize_byte(code: u32) -> Option<u8> {
    let byte = match code {
        0xF020..=0xF0FF => code - 0xF000,
        0x20..=0xFF => code,
        _ => return None,
    };
    u8::try_from(byte).ok()
}

/// Looks up a byte position in a byte-sorted `(byte, unicode)` table.
fn lookup(table: &[(u8, u32)], byte: u8) -> Option<u32> {
    table
        .binary_search_by_key(&byte, |&(b, _)| b)
        .ok()
        .map(|i| table[i].1)
}

/// Maps a legacy symbol font's code point to a Unicode scalar an ordinary text
/// face can render.
///
/// `font` is the declared family (e.g. `"Wingdings 2"`); `code` is the raw
/// `w:sym@char` / bullet code point (with or without the `0xF000` PUA offset).
/// Returns `None` when `(font, code)` is not a recognized symbol glyph — the
/// caller then leaves ordinary text untouched (a literal `•` or a numbered marker
/// must pass through unchanged).
#[must_use]
pub fn map_symbol(font: &str, code: u32) -> Option<char> {
    let family = classify(font)?;
    let byte = normalize_byte(code)?;
    let table = match family {
        Family::Symbol => SYMBOL,
        Family::Wingdings => WINGDINGS,
        Family::Wingdings2 => WINGDINGS2,
        Family::Wingdings3 => WINGDINGS3,
        Family::Webdings => WEBDINGS,
    };
    let scalar = coverage_fallback(lookup(table, byte)?);
    char::from_u32(scalar)
}

/// The visible glyph for an inline `w:sym`: the known Unicode mapping, or a
/// graceful fallback so the symbol is **never** silently dropped.
///
/// When `(font, code)` is not tabulated, the PUA offset is stripped and a
/// printable ASCII character is recovered if the result lands in `0x21..=0x7E`
/// (many symbol fonts alias ASCII letters/digits to pictographs; showing the
/// letter is more informative than a blank). An already-plain Unicode glyph is
/// returned as itself. Everything else becomes a visible `□` (U+25A1)
/// placeholder.
#[must_use]
pub fn resolve_symbol(font: &str, code: u32) -> char {
    if let Some(mapped) = map_symbol(font, code) {
        return mapped;
    }
    let candidate = normalize_byte(code).map_or(code, u32::from);
    match char::from_u32(candidate) {
        // A printable ASCII code recovered from the byte position.
        Some(c) if (0x21..=0x7E).contains(&candidate) => c,
        // An already-plain (non-PUA, non-control) Unicode glyph handed to `w:sym`.
        Some(c) if candidate > 0xFF && !is_private_use(candidate) && !c.is_control() => c,
        // An unmapped symbol/control/PUA code: a visible placeholder, not nothing.
        _ => '\u{25A1}',
    }
}

/// Whether a scalar value sits in a Unicode Private Use Area.
fn is_private_use(scalar: u32) -> bool {
    (0xE000..=0xF8FF).contains(&scalar)
        || (0xF_0000..=0xF_FFFD).contains(&scalar)
        || (0x10_0000..=0x10_FFFD).contains(&scalar)
}

/// Folds a mapped code point that Unicode assigned in a poorly-covered block down
/// to the well-covered Basic-Multilingual-Plane glyph that reads the same, so a
/// bundled/OS text face can actually draw it. Code points that ordinary fonts
/// already cover pass through unchanged; genuinely pictographic code points with
/// no BMP equivalent also pass through (rendering on a capable system font, else
/// a placeholder box). Glyph-fragment PUA targets become the `□` placeholder.
#[rustfmt::skip]
fn coverage_fallback(cp: u32) -> u32 {
    match cp {
        // Ballot boxes, checks, and crosses (Unicode-7 dingbats → BMP).
        0x1F5F8          => 0x2713, // ✓ light check → check mark
        0x1F5F4 | 0x1F5F6 => 0x2717, // ✗ script/bold ballot X
        0x1F5F9          => 0x2611, // ☑ ballot box with bold check
        0x1F5F5 | 0x1F5F7 => 0x2612, // ☒ ballot box with X
        0x2BBD | 0x2BBF   => 0x2612, // ☒ ballot/circled X variants
        0x2BBE           => 0x2297, // ⊗ circled X
        // Pointing hands (backhand index → white pointing hand).
        0x1F446 => 0x261D, // ☝ up
        0x1F447 => 0x261F, // ☟ down
        0x1F448 => 0x261C, // ☜ left
        0x1F449 => 0x261E, // ☞ right
        // Circles (size / weight variants → ● / ○ / ◉).
        0x26AB | 0x2B24 | 0x1F784 | 0x1F786 | 0x1F788 => 0x25CF, // ●
        0x26AA | 0x2B58 | 0x1F785 | 0x1F787 | 0x1F789 => 0x25CB, // ○
        0x1F78A | 0x1F78B => 0x25C9, // ◉ fisheye / round target
        // Squares (size / weight variants → ■ / □ / ▪).
        0x2B1B | 0x1F78C | 0x1F78D => 0x25A0, // ■
        0x2B1C | 0x1F78E | 0x1F78F | 0x1F790 | 0x1F791 | 0x1F792 | 0x1F793 => 0x25A1, // □
        0x2B1D | 0x2B1E => 0x25AA, // ▪ very small square
        // Diamonds and lozenges (→ ◆ / ◊).
        0x2B25 | 0x2B29 | 0x1F797 | 0x1F798 => 0x25C6, // ◆
        0x2B27 | 0x2B2A | 0x1F79D | 0x1F79E | 0x1F79F => 0x25CA, // ◊
        // Stars, asterisks, crosses, and saltires (many weights → BMP).
        0x1F7C0..=0x1F7D4 => 0x2605, // ★ black star family
        0x1F7AF..=0x1F7BF => 0x2733, // ✳ spoked asterisks
        0x1F7A1..=0x1F7A7 => 0x271A, // ✚ greek crosses
        0x1F7A8..=0x1F7AE => 0x2716, // ✖ saltires
        // Triangle-headed arrows (Wingdings 3 → BMP arrows).
        0x2B60 | 0x2B6A | 0x2B70 | 0x2B80 => 0x2190, // ←
        0x2B62 | 0x2B6C | 0x2B72         => 0x2192, // →
        0x2B61 | 0x2B6B | 0x2B71         => 0x2191, // ↑
        0x2B63 | 0x2B6D | 0x2B73         => 0x2193, // ↓
        0x2B64 => 0x2194, // ↔
        0x2B65 => 0x2195, // ↕
        0x2B66 | 0x2B76 => 0x2196, // ↖
        0x2B67          => 0x2197, // ↗
        0x2B69          => 0x2199, // ↙
        0x2B68 | 0x2B78 => 0x2198, // ↘
        // Black equilateral arrowheads / centred triangles → BMP triangles.
        0x2B9C | 0x1F780 | 0x2BC7 => 0x25C0, // ◀
        0x2B9E | 0x1F782 | 0x2BC8 => 0x25B6, // ▶
        0x2B9D | 0x1F781 | 0x2BC5 => 0x25B2, // ▲
        0x2B9F | 0x1F783 | 0x2BC6 => 0x25BC, // ▼
        // Any remaining glyph-fragment / unrenderable PUA target → placeholder.
        0xE000..=0xF8FF => 0x25A1, // □
        other => other,
    }
}

