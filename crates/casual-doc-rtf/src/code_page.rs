//! Accurate single-byte code-page tables for RTF `\'hh` decoding.
//!
//! RTF carries non-ASCII text either as a `\uN` Unicode escape or as raw
//! `\'hh` bytes in the code page the header (`\ansicpg`) or the run's font
//! (`\fcharset`) declares. Decoding those bytes against the wrong table
//! produces a document that opens with the wrong characters, which is worse
//! than one that refuses to open, so every table here was generated from the
//! authoritative Unicode mapping rather than typed by hand. Slots a code page
//! leaves undefined map to `None` and become a reported finding, never a
//! guessed character.
//!
//! Only single-byte code pages are tabulated. A double-byte code page (Shift
//! JIS 932, GBK 936, EUC-KR 949, Big5 950) needs a stateful multi-byte decoder
//! and is reported as unsupported instead of being decoded wrongly.

/// A single-byte code page's mapping for the high half (`0x80..=0xFF`).
///
/// The low half is US-ASCII in every code page RTF can declare here, so only
/// the 128 high slots are stored.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct CodePage {
    /// Windows code-page number as it appears in `\ansicpg`.
    pub number: u16,
    /// Human-readable name used in compatibility findings.
    pub name: &'static str,
    high: &'static [u16; 128],
}

impl CodePage {
    /// Decodes one byte, returning `None` when the code page leaves it undefined.
    #[must_use]
    pub fn decode(self, byte: u8) -> Option<char> {
        if byte < 0x80 {
            return Some(char::from(byte));
        }
        let scalar = self.high[usize::from(byte) - 0x80];
        if scalar == 0 {
            return None;
        }
        char::from_u32(u32::from(scalar))
    }
}

