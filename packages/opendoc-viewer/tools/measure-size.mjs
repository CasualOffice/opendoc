#!/usr/bin/env node
// SPDX-License-Identifier: Apache-2.0
//
// Measures the built Viewer SDK and publishes the numbers (docs/176 §4.5).
//
//   node tools/measure-size.mjs            measure pkg/ → size.json, regenerate the docs block
//   node tools/measure-size.mjs --check    fail if docs/176's block is not size.json's rendering
//
// A published number is generated from a committed artifact or it is not
// published (SKILL §9.1): `size.json` is that artifact, and the table in
// docs/176 between the `viewer-size` markers is rendered from it by this file,
// never typed. `--check` runs in the unit suite (test/size_record.test.mjs), so
// a hand edit to the table, or a size.json the table was not regenerated from,
// fails the build.
//
// Compression is Node's zlib: gzip at level 9 and brotli at quality 11, the
// settings `gzip -9` and `brotli -q 11` use. Section sizes are read from the
// module's own headers (code = section 10, data = section 11).
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { brotliCompressSync, constants, gzipSync } from "node:zlib";

const PACKAGE = join(dirname(fileURLToPath(import.meta.url)), "..");
const REPO = join(PACKAGE, "..", "..");
const PKG = join(PACKAGE, "pkg");
const RECORD = join(PACKAGE, "size.json");
const DOC = join(REPO, "docs", "176-THREE-SDK-PRODUCTS.md");
const BEGIN = "<!-- viewer-size:begin (generated by packages/opendoc-viewer/tools/measure-size.mjs; do not edit) -->";
const END = "<!-- viewer-size:end -->";

/** Size in bytes of each top-level section of a WebAssembly module, by id. */
export function wasmSections(bytes) {
  if (bytes.length < 8 || bytes.readUInt32BE(0) !== 0x0061736d) {
    throw new Error("not a WebAssembly module");
  }
  const sections = {};
  let at = 8;
  const leb = () => {
    let value = 0;
    let shift = 0;
    for (;;) {
      const byte = bytes[at++];
      value += (byte & 0x7f) * 2 ** shift;
      if ((byte & 0x80) === 0) return value;
      shift += 7;
    }
  };
  while (at < bytes.length) {
    const id = bytes[at++];
    const size = leb();
    sections[id] = (sections[id] ?? 0) + size;
    at += size;
  }
  return sections;
}

/** The measurement of one file. Brotli at quality 11 takes seconds on the
 *  module, so a caller that does not publish it can skip it. */
export function measure(bytes, { brotli = true } = {}) {
  return {
    raw: bytes.length,
    gzip: gzipSync(bytes, { level: 9 }).length,
    brotli: brotli && brotliCompressSync(bytes, {
      params: { [constants.BROTLI_PARAM_QUALITY]: 11, [constants.BROTLI_PARAM_SIZE_HINT]: bytes.length },
    }).length,
  };
}

function lockedVersion(name) {
  const lock = readFileSync(join(REPO, "Cargo.lock"), "utf8");
  const match = lock.match(new RegExp(`name = "${name}"\\nversion = "([^"]+)"`));
  return match ? match[1] : null;
}

function toolchain() {
  const text = readFileSync(join(REPO, "rust-toolchain.toml"), "utf8");
  return text.match(/channel\s*=\s*"([^"]+)"/)?.[1] ?? null;
}

/** Measures `pkg/` as built. */
export function measurePackage(features) {
  const wasm = readFileSync(join(PKG, "opendoc_viewer_bg.wasm"));
  const glue = readFileSync(join(PKG, "opendoc_viewer.js"));
  const sections = wasmSections(wasm);
  const fontsDir = join(PKG, "fonts");
  const fonts = readdirSync(fontsDir)
    .filter((name) => name.endsWith(".ttf"))
    .sort()
    .map((name) => ({ name, ...measure(readFileSync(join(fontsDir, name))) }));
  const sum = (key) => fonts.reduce((total, font) => total + font[key], 0);
  return {
    features,
    toolchain: toolchain(),
    wasmBindgen: lockedVersion("wasm-bindgen"),
    module: { ...measure(wasm), code: sections[10] ?? 0, data: sections[11] ?? 0 },
    glue: measure(glue),
    hostFonts: { files: fonts.length, raw: sum("raw"), gzip: sum("gzip"), brotli: sum("brotli") },
  };
}

const n = (value) => value.toLocaleString("en-US");

/** The docs/176 block for a record. */
export function renderBlock(record) {
  const m = record.module;
  const g = record.glue;
  const f = record.hostFonts;
  return [
    BEGIN,
    "",
    `Built by \`packages/opendoc-viewer/build.sh\` with features \`${record.features}\`, Rust ${record.toolchain}, wasm-bindgen ${record.wasmBindgen}; gzip level 9 and brotli quality 11 (Node zlib).`,
    "",
    "| Artefact | Raw | gzip | brotli | code section | data section |",
    "| --- | ---: | ---: | ---: | ---: | ---: |",
    `| \`opendoc_viewer_bg.wasm\` (engine + core font) | ${n(m.raw)} | ${n(m.gzip)} | ${n(m.brotli)} | ${n(m.code)} | ${n(m.data)} |`,
    `| \`opendoc_viewer.js\` (glue) | ${n(g.raw)} | ${n(g.gzip)} | ${n(g.brotli)} | | |`,
    `| \`pkg/fonts/\` (${f.files} host-served faces, fetched only when a document needs them) | ${n(f.raw)} | ${n(f.gzip)} | ${n(f.brotli)} | | |`,
    "",
    END,
  ].join("\n");
}

function replaceBlock(doc, block) {
  const start = doc.indexOf(BEGIN);
  const end = doc.indexOf(END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error("docs/176 has no viewer-size block (the BEGIN/END markers)");
  }
  return doc.slice(0, start) + block + doc.slice(end + END.length);
}

/** Whether docs/176's block is exactly the rendering of size.json. */
export function docsMatchRecord() {
  const record = JSON.parse(readFileSync(RECORD, "utf8"));
  const doc = readFileSync(DOC, "utf8");
  return replaceBlock(doc, renderBlock(record)) === doc;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    if (!docsMatchRecord()) {
      console.error("docs/176's viewer-size block is not size.json's rendering; run tools/measure-size.mjs");
      process.exit(1);
    }
  } else {
    statSync(join(PKG, "opendoc_viewer_bg.wasm"));
    const record = measurePackage(process.env.VIEWER_FEATURES ?? "wasm,core-fonts,pdf");
    writeFileSync(RECORD, `${JSON.stringify(record, null, 2)}\n`);
    writeFileSync(DOC, replaceBlock(readFileSync(DOC, "utf8"), renderBlock(record)));
    console.log(renderBlock(record));
  }
}
